-- Derruba UNIQUE (constraint ou índice, não parcial) cujas colunas sejam EXATAMENTE `cols`.
CREATE FUNCTION pg_temp.drop_unique(tbl text, cols text[]) RETURNS void LANGUAGE plpgsql AS $$
DECLARE r record; rel regclass := to_regclass('public.' || tbl); want text;
BEGIN
  IF rel IS NULL THEN RETURN; END IF;
  SELECT string_agg(x, ',' ORDER BY x) INTO want FROM unnest(cols) x;
  FOR r IN
    SELECT c.conname FROM pg_constraint c
    WHERE c.conrelid = rel AND c.contype = 'u'
      AND (SELECT string_agg(a.attname::text, ',' ORDER BY a.attname)
           FROM unnest(c.conkey) k JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = k) = want
  LOOP
    EXECUTE format('ALTER TABLE %s DROP CONSTRAINT %I', rel, r.conname);
  END LOOP;
  FOR r IN
    SELECT i.indexrelid::regclass AS idx FROM pg_index i
    WHERE i.indrelid = rel AND i.indisunique AND NOT i.indisprimary
      AND i.indpred IS NULL AND i.indexprs IS NULL
      AND (SELECT string_agg(a.attname::text, ',' ORDER BY a.attname)
           FROM unnest(i.indkey::int2[]) k JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = k) = want
  LOOP
    EXECUTE format('DROP INDEX %s', r.idx);
  END LOOP;
END $$;

-- Troca a PK por `cols` (só age se a tabela JÁ tem PK e ela ainda não é `cols`).
CREATE FUNCTION pg_temp.set_pk(tbl text, cols text[]) RETURNS void LANGUAGE plpgsql AS $$
DECLARE rel regclass := to_regclass('public.' || tbl); pkname text; have text; want text;
BEGIN
  IF rel IS NULL THEN RETURN; END IF;
  SELECT c.conname,
         (SELECT string_agg(a.attname::text, ',' ORDER BY a.attname)
          FROM unnest(c.conkey) k JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = k)
    INTO pkname, have
  FROM pg_constraint c WHERE c.conrelid = rel AND c.contype = 'p';
  IF pkname IS NULL THEN RETURN; END IF;
  SELECT string_agg(x, ',' ORDER BY x) INTO want FROM unnest(cols) x;
  IF have = want THEN RETURN; END IF;
  EXECUTE format('ALTER TABLE %s DROP CONSTRAINT %I', rel, pkname);
  EXECUTE format('ALTER TABLE %s ADD PRIMARY KEY (%s)', rel, (SELECT string_agg(quote_ident(x), ',') FROM unnest(cols) x));
END $$;

-- Índice único (store_id) para tabelas "uma linha por loja"; avisa em vez de falhar se houver duplicatas.
CREATE FUNCTION pg_temp.unique_per_store(tbl text) RETURNS void LANGUAGE plpgsql AS $$
DECLARE n bigint;
BEGIN
  IF to_regclass('public.' || tbl) IS NULL THEN RETURN; END IF;
  EXECUTE format('SELECT COUNT(*) - COUNT(DISTINCT store_id) FROM %I', tbl) INTO n;
  IF n > 0 THEN
    RAISE NOTICE 'ATENÇÃO: % tem % linha(s) duplicada(s) por loja — UNIQUE(store_id) NÃO criado; limpe e rode de novo.', tbl, n;
  ELSE
    EXECUTE format('CREATE UNIQUE INDEX IF NOT EXISTS %I ON %I (store_id)', tbl || '_one_per_store', tbl);
  END IF;
END $$;

