-- Cria `stores`, adiciona `store_id` (DEFAULT 1 = loja atual) em todas as
-- tabelas por-loja, troca as constraints UNIQUE globais por UNIQUE por loja
-- e cria triggers que impedem referência cruzada entre lojas.
--
-- Nada aqui muda o comportamento da loja atual: todas as linhas existentes
-- ficam com store_id = 1 e os INSERTs antigos (que não informam store_id)
-- continuam funcionando por causa do DEFAULT 1.
--
-- Rode a FASE 2 (2026-09-25_multi_tenant_phase2.sql) só depois que o código
-- passar store_id em toda query — ela remove o DEFAULT e liga o RLS.
--
-- Idempotente e transacional (tudo ou nada). Tabelas que não existirem no
-- seu banco (criadas sob demanda pelos ensure*()) são simplesmente puladas.
-- =====================================================================

